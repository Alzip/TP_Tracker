#!/usr/bin/env python3
"""Materialize the audited TPTracker ko3 source in GitHub Actions.

Takes a compact patch against a pinned 2026 normal-game commit, and a JSON
translation overlay against the pinned ko2 dictionary. Refuses source drift.
The native GX font atlas is regenerated by the repository's font builder.
"""
import base64
import hashlib
import io
import json
import lzma
import pathlib
import re
import subprocess
import tarfile

ROOT = pathlib.Path(__file__).resolve().parents[2]
BASE = '821dc49c6008'  # normal-game code before translation
PACK_SHA = '43bcea2ab4fc9911b72941e84cd0656e793242a11e10026a9eda762201d4cba8'
EXPECTED = {
    'CMakeLists.txt': 'd7cffcb07e4b16748057c56c466580beb2d8a8b5',
    'mod.json': 'ced59652dc5b2a84ed2a419a641dc9146658ea00',
    'src/localization.hpp': '7bc4a582e06561680fc95cc0136e2e198e4222af',
    'src/localized_controls.hpp': 'b25478c390699866e7e88055eb55242aa29830b9',
    'src/map.cpp': '8556c75a79675d8fef82a7b5dbf0b4670ca2b265',
    'src/map.hpp': 'd615e1a11fb8ce8762ecbdd4ad6902c5688d29d5',
    'src/mod.cpp': '1f5851d8ab865b78a5a599678acda2d1c50883f0',
    'tests/localization_tests.cpp': '7aa9e02159ec1e61427725f83d27d912dd34e1a3',
    'tests/localized_controls_tests.cpp': 'e15222f4b84cdabf8dd4d387876c8adfeb662cec',
    'tests/map_text_tests.cpp': '9810c864e89c4fb7aef73a5b766ee79a725584b7',
}
HUNK = re.compile(r'^@@ -(\d+)(?:,(\d+))? \+(\d+)(?:,(\d+))? @@')


def git_bytes(*args):
    return subprocess.check_output(['git','-C',str(ROOT),*args], stderr=subprocess.DEVNULL)


def blob_sha(data):
    return hashlib.sha1(b'blob ' + str(len(data)).encode() + b'\0' + data).hexdigest()


def patch_files(patch):
    lines = patch.splitlines(keepends=True)
    ix = 0
    while ix < len(lines):
        if not lines[ix].startswith('--- a/') or ix+1 >= len(lines) or not lines[ix+1].startswith('+++ b/'):
            raise RuntimeError(f'Unexpected patch header at line {ix}: {lines[ix][:80]!r}')
        path = lines[ix+1][6:].rstrip('\r\n')
        if lines[ix][6:].rstrip('\r\n') != path or path not in EXPECTED:
            raise RuntimeError('Unexpected patch path: ' + path)
        ix += 2
        hunks = []
        while ix < len(lines) and lines[ix].startswith('@@ '):
            m=HUNK.match(lines[ix]);
            if not m: raise RuntimeError('Bad patch hunk')
            start=int(m.group(1)); old_count=int(m.group(2) or 1)
            new_count=int(m.group(4) or 1)
            ix+=1
            operations=[]; consumed=0; produced=0
            while ix < len(lines) and not lines[ix].startswith(('@@ ', '--- a/')):
                line=lines[ix]; ix+=1
                if line.startswith('-'): consumed+=1
                elif line.startswith('+'): produced+=1
                elif line.startswith(' '): consumed+=1;produced+=1
                else: raise RuntimeError('Malformed hunk line')
                operations.append(line)
            if consumed != old_count or produced != new_count:
                raise RuntimeError(f'Hunk length mismatch in {path}: {consumed}/{old_count}, {produced}/{new_count}')
            hunks.append((start,old_count,operations))
        yield path,hunks


def apply_patch(path,hunks):
    try:
        original=git_bytes('show',f'{BASE}:{path}').decode('utf-8').splitlines(keepends=True)
    except subprocess.CalledProcessError:
        original=[]
    written=[]; cursor=0
    for line,old_count,operations in hunks:
        index=(line if old_count == 0 else line-1)
        if index<cursor or index>len(original):raise RuntimeError('Out of order patch hunk: '+path)
        written.extend(original[cursor:index]); cursor=index
        for op in operations:
            marker,content=op[0],op[1:]
            if marker in (' ','-'):
                if cursor>=len(original) or original[cursor]!=content:
                    raise RuntimeError(f'Patch baseline changed: {path}, line {cursor+1}')
                cursor+=1
            if marker in (' ','+'):
                written.append(content)
    written.extend(original[cursor:])
    data=''.join(written).encode('utf-8')
    if blob_sha(data)!=EXPECTED[path]:
        raise RuntimeError(f'Result differs from audited ko3 file: {path}')
    dest=ROOT/path
    dest.parent.mkdir(parents=True,exist_ok=True)
    dest.write_bytes(data)
    print('Verified ko3 source:',path)


def main():
    transfer=(ROOT/'tools/ko3/ko3-bootstrap.b85').read_text(encoding='ascii').strip()
    compressed=base64.b85decode(transfer)
    if hashlib.sha256(compressed).hexdigest()!=PACK_SHA:
        raise RuntimeError('ko3 bootstrap archive checksum mismatch')
    with tarfile.open(fileobj=io.BytesIO(lzma.decompress(compressed)),mode='r:') as archive:
        entries={x.name:archive.extractfile(x).read() for x in archive.getmembers() if x.isfile()}
    if sorted(entries)!=['code.patch','overlay.json']:
        raise RuntimeError('Unexpected bootstrap contents')
    files=dict(patch_files(entries['code.patch'].decode('utf-8')))
    if set(files)!=set(EXPECTED):
        raise RuntimeError('ko3 source file inventory mismatch')
    for path,hunks in files.items():
        apply_patch(path,hunks)
    overlay=json.loads(entries['overlay.json'])
    path=ROOT/'res/ko.json'
    original=path.read_bytes()
    if hashlib.sha256(original).hexdigest()!=overlay['base_ko2_sha256']:
        raise RuntimeError('Unexpected ko2 localization baseline')
    locale=json.loads(original)
    for section,items in overlay['overlay'].items():
        if section not in ('names','strings') or not isinstance(items,dict):
            raise RuntimeError('Unexpected translation section')
        locale[section].update(items)
    output=(json.dumps(locale,ensure_ascii=False,indent=2)+'\n').encode('utf-8')
    if hashlib.sha256(output).hexdigest()!=overlay['target_ko3_sha256']:
        raise RuntimeError('Translation does not match audited ko3 source')
    path.write_bytes(output)
    print('Verified ko3 localization dictionary')

if __name__ == '__main__':main()
